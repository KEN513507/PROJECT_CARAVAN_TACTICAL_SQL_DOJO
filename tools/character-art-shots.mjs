import { chromium } from 'playwright';
import { boot, source, run } from './onboarding-ui-helpers.mjs';
const dir = 'tools/ux-artifacts/character';
const b = await chromium.launch();
const c = await b.newContext({ viewport:{width:390,height:844}, hasTouch:true });
const p = await c.newPage();
await boot(p);
await p.waitForTimeout(800);
await p.screenshot({ path: `${dir}/01-intro.png` });
await source(p, 0);
await p.waitForTimeout(700);
await p.screenshot({ path: `${dir}/02-editing.png` });
await p.locator('#hintBtn').click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${dir}/03-hint.png` });
await p.locator('#hintBtn').click();
await run(p);
await p.waitForTimeout(800);
await p.screenshot({ path: `${dir}/04-clear.png` });
await b.close();
console.log('shots ok');
